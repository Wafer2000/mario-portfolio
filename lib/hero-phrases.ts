const HISTORY_KEY = "mario-portfolio-hero-history-v1";
const HISTORY_LIMIT = 16;

function randomIndex(length: number): number {
  if (length <= 1) return 0;
  try {
    const values = new Uint32Array(1);
    window.crypto.getRandomValues(values);
    return values[0] % length;
  } catch {
    return Math.floor(Math.random() * length);
  }
}

export function pickHeroPhraseIndex(): number {
  const total = heroPhrases.length;
  if (total <= 1) return 0;

  let recent: number[] = [];
  try {
    const parsed = JSON.parse(localStorage.getItem(HISTORY_KEY) ?? "[]");
    if (Array.isArray(parsed)) {
      recent = parsed.filter((value): value is number => Number.isInteger(value) && value >= 0 && value < total).slice(0, HISTORY_LIMIT);
    }
  } catch {}

  let candidates = Array.from({ length: total }, (_, index) => index).filter(index => !recent.includes(index));
  if (candidates.length === 0) {
    const last = recent[0];
    candidates = Array.from({ length: total }, (_, index) => index).filter(index => index !== last);
  }

  const selected = candidates[randomIndex(candidates.length)] ?? 0;
  try {
    localStorage.setItem(HISTORY_KEY, JSON.stringify([selected, ...recent.filter(index => index !== selected)].slice(0, HISTORY_LIMIT)));
  } catch {}
  return selected;
}
